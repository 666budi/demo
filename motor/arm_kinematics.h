/**
 * @file arm_kinematics.h
 * @author xioafo
 * @brief  三自由度机械臂末端位姿正解
 * @note   两级解算，全部为闭式公式，无迭代：
 *           第 1 级  电机输出轴角 -> 关节角
 *                    q_k = ARM_DIR_k * (out_rad_k - O_k) / ARM_RATIO_k
 *           第 2 级  关节角 -> 末端位姿
 *                    phi1  = ARM_PHI1_0 + q1
 *                    phi2  = ARM_PHI2_0 + q1 + q2
 *                    phi3  = ARM_PHI3_0 + q1 + q2 + q3
 *                    x     = L1*cos(phi1) + L2*cos(phi2) + L3*cos(phi3)
 *                    z     = ARM_H + L1*sin(phi1) + L2*sin(phi2) + L3*sin(phi3)
 *                    theta = phi3 + ARM_DELTA
 * @details 机械结构前提（上机前必须为真）：
 *            1. 三个转轴互相平行，整条臂共面，故 y 恒为 0；
 *            2. 肩(电机0)/肘(电机1)/腕(电机2) 是串链上的三个物理铰链，关节角为
 *               "相对角"（相对上一根连杆）——所以转电机1时大臂不动、小臂和末端
 *               一起转；转电机2时只有末端转；
 *            3. 上电时臂处于标准直角位：大臂竖直向上、小臂水平前伸、末端与小臂
 *               同向（ARM_PHI3_0 = 0）。整套解算的零位就锚在这一位形上。
 *
 *          坐标系：
 *            O = 肩关节轴线在地面的投影点；x 水平向前（直角位小臂伸出方向）；
 *            y 沿转轴方向（平面臂恒为 0）；z 竖直向上。
 *            TCP = Tool Center Point，末端连杆尖端；
 *            theta = 末端连杆方向相对 +x 轴的角度。
 *
 *          为什么 O_k 必须运行期实测而不能只靠宏：
 *            out_rad 的零点不是机械绝对基准。total_rad 从"第一帧反馈"起算
 *            （damiao_motor.c 中第一帧只赋 last_pos、不累加），而
 *            DamiaoMotor_SavePositionZero() 几乎同时在开机时下发，两者先后
 *            决定 total_rad 在标定时刻是 0 还是 -X。对 S 系列（电机2 是
 *            S2325，增量式编码器）这个零点更是只对应"上电那一瞬间"。
 *            故 O_k 每次上电实测；第二节的宏只存"预期值"，用于自检。
 */
#ifndef __ARM_KINEMATICS_H
#define __ARM_KINEMATICS_H

#include "damiao_motor.h" /* 提供 DAMIAO_PI */

/* ==========================================================================
 *  一、编译期开关
 * ========================================================================== */

/* 上电零位 O_k 的来源。建议保持 0：抓取版本可以在 VOFA/调试器里看到实际值，
 * 也能把"上电时臂不在直角位"这个最危险的失效模式变成可见的 */
#define ARM_USE_FIXED_ZERO 0 /* 0 = 每次上电抓取 out_rad 快照并与 ARM_ZERO_* 比对；1 = 直接使用 ARM_ZERO_*，不抓取 */

/* ==========================================================================
 *  二、上电零位预期值（单位 rad，电机输出轴侧）
 *  标定方法：保持 ARM_USE_FIXED_ZERO = 0、把 ARM_TELEMETRY_MODE 设为 1，
 *  上电后 arm_zero_snapshot[0..2] 就是从 VOFA 读到的 O_k，把数抄回这里。
 *  偏差超过 ARM_ZERO_TOL 时 arm_zero_ok 会置 0，说明上电位形不对。
 * ========================================================================== */

#define ARM_ZERO_0 0.0f     /* 电机0(肩) 在直角位时的 out_rad 预期值 (rad) */
#define ARM_ZERO_1 0.0f     /* 电机1(肘) 在直角位时的 out_rad 预期值 (rad) */
#define ARM_ZERO_2 0.0f     /* 电机2(腕) 在直角位时的 out_rad 预期值 (rad) */
#define ARM_ZERO_TOL 0.05f  /* O_k 实测值与预期值的允许偏差 (rad)，超差则 arm_zero_ok = 0 */

/* ==========================================================================
 *  三、几何参数（单位 m）
 *  量的是"关节轴中心距"，不是连杆外形尺寸，三维模型里读最准
 * ========================================================================== */

#define ARM_H 0.0f   /* 肩关节轴线离地面的高度 */
#define ARM_L1 0.45f /* 肩轴 -> 肘轴 的中心距 */
#define ARM_L2 0.45f /* 肘轴 -> 腕轴 的中心距 */
#define ARM_L3 0.0f  /* 腕轴 -> 末端尖端(TCP) 的中心距，当前 TCP 即腕轴点 */

/* ==========================================================================
 *  四、传动比：电机输出轴 -> 关节（同步带/齿轮/链这一级）
 *  不含电机内置减速器！damiao_motor.c 里 out_rad 已经除过 reduction_ratio
 *  （25.0 / 1.0 / 1.0），这里再乘一次就是重复缩放。
 *  若电机输出轴直接就是关节轴，填 1.0f 即可。
 * ========================================================================== */

#define ARM_RATIO_0 1.0f /* 电机0输出轴 -> 肩关节 的传动比 */
#define ARM_RATIO_1 1.0f /* 电机1输出轴 -> 肘关节 的传动比 */
#define ARM_RATIO_2 1.0f /* 电机2输出轴 -> 腕关节 的传动比 */

/* ==========================================================================
 *  五、方向符号（+1.0f / -1.0f）
 *  必须上机实测，由装配方向和接线决定
 *  实测方法：给该电机一个很小的正 target_pos，看关节往哪边转
 *  注意 rc_task.c 里 target_pos 是"转子侧"弧度（电机2 那行乘了 25），
 *  而 out_rad 是输出侧，两者差一个 reduction_ratio
 * ========================================================================== */

#define ARM_DIR_0 (-1.0f) /* 电机0(肩) 实测转向符号 */
#define ARM_DIR_1 (+1.0f) /* 电机1(肘) 实测转向符号 */
#define ARM_DIR_2 (+1.0f) /* 电机2(腕) 实测转向符号 */

/* ==========================================================================
 *  六、角度基准与工具坐标偏置
 *  ARM_PHI1_0/2_0/3_0 描述"直角零位"时三根连杆的绝对角度，不是可随便调的
 *  量：它们和 O_k 是绑死的——改了它们就等于宣称标定位形是另一个姿态
 * ========================================================================== */

#define ARM_DELTA 0.0f               /* 末端连杆方向 -> 姿态角 theta 的安装偏置 (rad) */
#define ARM_PHI1_0 (DAMIAO_PI * 0.5f) /* 直角零位时大臂的绝对角，竖直向上 = +90 度 (rad) */
#define ARM_PHI2_0 0.0f              /* 直角零位时小臂的绝对角，水平前伸 = 0 度 (rad) */
#define ARM_PHI3_0 0.0f              /* 直角零位时末端的绝对角，与小臂同向 = 0；反向填 DAMIAO_PI */
#define ARM_TCP_LX 0.0f              /* 工具偏置：沿末端轴向的分量 (m) */
#define ARM_TCP_LZ 0.0f              /* 工具偏置：垂直末端轴向的分量 (m)，逆时针为正 */

/* ==========================================================================
 *  七、遥测
 * ========================================================================== */

#define ARM_TELEMETRY_MODE 0      /* 0 = 发 (x[mm], z[mm], theta[deg])；1 = 发 O_k 三个读数用于标定零位 */
#define ARM_TELEMETRY_PERIOD_MS 5 /* arm_task 循环周期 (ms)。vofa_send 是阻塞式单次发送，周期太小会长时间占用 UART，按波特率调整 */

/* ==========================================================================
 *  八、运行期参数表
 *  宏是"出厂默认值"，这张表是"工作副本"。表刻意不是 const，可以在 Keil
 *  调试器的 Watch 窗口里直接改（比如把 ratio[2] 从 1.0 慢慢调到 25.0），
 *  立即从 VOFA 看到效果，不用重编译重新烧录；调好后把值回填到上面的宏。
 *  必须放在文件作用域，不要放 arm_task 局部变量——arm_task 栈只有 1024 字节。
 * ========================================================================== */
typedef struct
{
    float h;                   /* 肩关节轴线高度 (m) */
    float l1, l2, l3;          /* 三根连杆的关节轴中心距 (m) */
    float ratio[3];            /* 电机输出轴 -> 关节 的传动比 */
    float dir[3];              /* 方向符号 (+1 / -1) */
    float delta;               /* 末端连杆方向 -> 姿态角 的安装偏置 (rad) */
    float phi10, phi20, phi30; /* 直角零位下三根连杆的绝对角 (rad) */
    float tcp_lx, tcp_lz;      /* 末端坐标系下的工具坐标偏置 (m) */
} ArmParams_t;

/* ==========================================================================
 *  九、解算结果
 * ========================================================================== */
typedef struct
{
    float x, y, z;   /* TCP 坐标 (m)，y 恒为 0 */
    float theta;     /* 姿态角，末端方向相对 +x 轴 (rad) */
    float theta_deg; /* 同上，单位度 */
    float q[3];      /* 关节角 q1/q2/q3 (rad) */
    float phi[3];    /* 三根连杆的绝对角 phi1/phi2/phi3 (rad) */
    uint8_t valid;   /* 1 = 已标定且三个电机都在线 */
    uint8_t zero_ok; /* 1 = 上电零位与 ARM_ZERO_* 预期值一致 */
} ArmPose_t;

/* ==========================================================================
 *  十、对外变量
 * ========================================================================== */

extern ArmParams_t arm_params; /* 运行期参数工作副本（非 const，调试器可实时改） */

extern ArmPose_t arm_pose; /* 最新一次解算结果 */

extern float arm_zero_snapshot[3]; /* 上电标定抓到的 O_k，ARM_TELEMETRY_MODE=1 时从 VOFA 读出 */

extern float arm_zero_deviation[3]; /* 上电标定时 实测值 - 预期值 (rad) */

extern uint8_t arm_zero_ok; /* 上电零位自检结果，1 = 与预期值一致 */

/* ==========================================================================
 *  十一、对外接口
 * ========================================================================== */

/**
 * @brief  把 arm_params 全部恢复成上面那些宏的出厂默认值
 */
void ArmKinematics_ResetParams(void);

/**
 * @brief  上电零位标定，抓取 O_k
 * @return 1 = 三个电机都 is_online 且已收到第一帧，快照已抓取
 *         0 = 条件未满足，调用方应延时重试
 * @note   运行期不要再次调用，会把零位搬走
 */
uint8_t ArmKinematics_CalibrateZero(void);

/**
 * @brief 读一次三路 out_rad，算出关节角并更新 arm_pose，建议放在周期任务里调用
 */
void ArmKinematics_Update(void);

/**
 * @brief  纯函数：关节角 -> 位姿，不读电机、不写 valid，便于离线/上台架验证
 * @param  q1  肩关节角 (rad)
 * @param  q2  肘关节角 (rad)
 * @param  q3  腕关节角 (rad)
 * @param  out 解算结果输出，不可为 NULL
 */
void ArmKinematics_Solve(float q1, float q2, float q3, ArmPose_t *out);

#endif /* __ARM_KINEMATICS_H */
